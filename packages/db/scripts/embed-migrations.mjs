// Regenerates src/migrationSql.generated.ts from migrations/*.sql, in journal order.
// Run this after `drizzle-kit generate` produces a new migration file.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const migrationsDir = join(here, '..', 'migrations')
const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'))

const files = journal.entries.map((e) => `${e.tag}.sql`)
const missing = files.filter((f) => !readdirSync(migrationsDir).includes(f))
if (missing.length > 0) throw new Error(`Migration files listed in journal but missing on disk: ${missing.join(', ')}`)

const sqls = files.map((f) => readFileSync(join(migrationsDir, f), 'utf8'))

const out = `// GENERATED by scripts/embed-migrations.mjs — do not edit by hand.
// Migration SQL embedded as string literals so the pglite dev/test DB never needs to
// resolve a filesystem path at runtime (that breaks once this code is bundled by Next.js).
export const MIGRATION_SQLS: string[] = ${JSON.stringify(sqls, null, 2)}
`

writeFileSync(join(here, '..', 'src', 'migrationSql.generated.ts'), out)
console.log(`Embedded ${sqls.length} migration file(s) into src/migrationSql.generated.ts`)
